/* cpu.h - NEC 78K/III (uPD78312A) cpu-description header for vasm
 *
 * The opcode table, operand-type enum and address math (shared/Opcodes.h,
 * shared/Operand.h, shared/Addressing.h) are the same as the standalone
 * NEC_78KIII_Disassembler's. They are separate copies, kept identical by
 * hand (only the mnemonic prefix and comments differ), so a fix to one
 * must be carried to the other.
 */

#define LITTLEENDIAN 1
#define BIGENDIAN 0
#define BITSPERBYTE 8
#define VASM_CPU_78K3 1

/* up to 3 operands per instruction, matching Opcode.operand1/2/3 */
#define MAX_OPERANDS 3

/* NEC bit-operand syntax (set1 flags.3, bt flags.3,label, mov1 cy,flags.3,
 * and1 cy,/flags.3): rewritten into this backend's own form before the
 * operands are matched. Called by the std syntax module. See cpu.c. */
void cpu_fixup_bit_syntax(char **inst, int *inst_len, char **op, int *op_len, int *op_cnt);

/* PUSH/POP's register-list operand (OT_POST_BYTE/_U) is written as a
 * single brace-delimited, comma-separated field -- "push {ax,bc,de,hl}" --
 * rather than as several top-level operands, since MAX_OPERANDS==3 can't
 * hold up to 4-6 comma-separated register names anyway. Counting '{'/'}'
 * as parens makes the std syntax module's skip_operand() (syntax.c) treat
 * the whole list as one operand field instead of splitting on its internal
 * commas -- the exact same trick the ARM backend uses for "{r0,r1,r2}".
 * cpu.c's parse_operand() then strips the braces and parses the list
 * itself. See cpu.c's OT_POST_BYTE comment. */
#define START_PARENTH(x) ((x)=='(' || (x)=='{')
#define END_PARENTH(x) ((x)==')' || (x)=='}')

/* no mnemonic qualifiers (.b/.w etc) -- word-sized ops are distinct
 * mnemonics on this cpu (MOVW vs MOV, ADDW vs ADD, ...) */
#define MAX_QUALIFIERS 0

#include <stdint.h>
typedef int32_t taddr;
typedef uint32_t utaddr;

/* byte-addressed, no alignment requirement */
#define INST_ALIGN 1
#define DATA_ALIGN(n) 1

/* operand class used for plain data (dc.b/dc.w/...) definitions --
 * deliberately outside the range of real OT_* values (all of which are
 * small non-negative ints; see shared/Operand.h), so it can never be
 * confused with a real instruction-operand type. */
#define OP_DATA_ABS (-1)
#define DATA_OPERAND(n) OP_DATA_ABS

/* Reuse operands only once per parse attempt -- simpler than tracking
 * partial state across PO_COMB_* combos, and none of our operand types
 * need that mechanism. */
#define CLEAR_OPERANDS_ON_MNEMO 1

/* parsed operand instance */
typedef struct {
  int type;     /* OT_* from shared/Operand.h, or OP_DATA_ABS */
  int reg;      /* register/field value, for register-type operands */
  expr *val;    /* expression, for value/address/bit-number operands */
} operand;

/* mnemonic table extension: which row of the shared opps[] table
 * (shared/Opcodes.h) this mnemonic-table entry was generated from. See
 * cpus/78k3/mnemonics_gen.c (auto-generated by gen_mnemonics.c). */
typedef struct {
  int opcode_idx;
} mnemonic_extension;
